#' Add year-sensitive CoW or Gleditsch-Ward country codes
#'
#' `ucdp_country_crosswalk()` adds the counterpart to a Correlates of War
#' (`ccode`) or Gleditsch-Ward (`gwcode`) identifier. By default it obtains a
#' year-sensitive mapping from `peacesciencer::create_stateyears()` and
#' `peacesciencer::add_gwcode_to_cow()` or
#' `peacesciencer::add_ccode_to_gw()`. A supplied crosswalk makes the operation
#' fully offline and is useful when freezing a replication workflow.
#'
#' @param data A data frame containing a country code and year.
#' @param from Coding system used by `code`: `"gw"` or `"cow"`.
#' @param code,year Names of the source-code and year columns. Common UCDP names
#'   are detected when `code` is omitted.
#' @param crosswalk Optional data frame containing `year`, `gwcode`, and
#'   `ccode`. If omitted, the mapping is generated by `peacesciencer`.
#' @param unmatched How to handle rows without a counterpart: retain them with
#'   `NA`, warn and retain them, drop them, or raise an error.
#' @return A tibble with the original rows and a `gwcode` or `ccode` column.
#'   The `ucdp_source` attribute is preserved and matching diagnostics are
#'   stored in `ucdp_crosswalk`.
#' @export
#' @examples
#' x <- data.frame(country_id = c(2, 20, 999), year = 2020)
#' map <- data.frame(
#'   year = c(2020, 2020), gwcode = c(2, 20), ccode = c(2, 20)
#' )
#' ucdp_country_crosswalk(x, from = "gw", crosswalk = map)
ucdp_country_crosswalk <- function(data, from = c("gw", "cow"), code = NULL,
                                   year = "year", crosswalk = NULL,
                                   unmatched = c("keep", "warn", "drop", "error")) {
  if (!is.data.frame(data)) cli::cli_abort("{.arg data} must be a data frame.")
  from <- match.arg(from)
  unmatched <- match.arg(unmatched)
  year <- scalar_column(data, year, "year")
  candidates <- if (from == "gw") c("gwcode", "gwno", "country_id") else c("ccode")
  code <- resolve_interop_column(data, code, candidates, "code")
  source <- attr(data, "ucdp_source", exact = TRUE)

  years <- integer_value(data[[year]], year)
  codes <- integer_value(data[[code]], code)
  supplied_crosswalk <- !is.null(crosswalk)
  if (!supplied_crosswalk) crosswalk <- peacesciencer_crosswalk(years, from)
  crosswalk <- validate_country_crosswalk(crosswalk)
  target <- if (from == "gw") "ccode" else "gwcode"
  if (target %in% names(data) && target != code) {
    cli::cli_abort("{.arg data} already contains the target column {.field {target}}.")
  }

  key <- paste(codes, years, sep = "\r")
  map_key <- paste(crosswalk[[if (from == "gw") "gwcode" else "ccode"]],
                   crosswalk$year, sep = "\r")
  duplicated_keys <- unique(map_key[duplicated(map_key)])
  if (length(duplicated_keys)) {
    cli::cli_abort("{.arg crosswalk} contains duplicate source-code/year keys.")
  }
  matched <- match(key, map_key)
  out <- as.data.frame(data, stringsAsFactors = FALSE)
  out[[target]] <- crosswalk[[target]][matched]
  missed <- is.na(matched) & !is.na(codes) & !is.na(years)
  n_missed <- sum(missed)
  if (n_missed && unmatched == "error") {
    cli::cli_abort("No country-code match was found for {n_missed} row(s).")
  }
  if (n_missed && unmatched == "warn") {
    cli::cli_warn("No country-code match was found for {n_missed} row(s); the new code is NA.")
  }
  if (unmatched == "drop") out <- out[!missed, , drop = FALSE]
  out <- tibble::as_tibble(out)
  if (!is.null(source)) attr(out, "ucdp_source") <- source
  attr(out, "ucdp_crosswalk") <- list(
    from = from, to = if (from == "gw") "cow" else "gw",
    code = code, year = year, matched = sum(!is.na(matched)), unmatched = n_missed,
    source = if (supplied_crosswalk) "supplied" else "peacesciencer"
  )
  out
}

peacesciencer_crosswalk <- function(years, from) {
  require_optional("peacesciencer", "construct a year-sensitive country-code crosswalk")
  wanted <- sort(unique(years[!is.na(years)]))
  if (!length(wanted)) cli::cli_abort("No non-missing years are available for the crosswalk.")
  base <- peacesciencer::create_stateyears(
    system = from, mry = TRUE, subset_years = wanted
  )
  if (from == "gw") peacesciencer::add_ccode_to_gw(base) else peacesciencer::add_gwcode_to_cow(base)
}

validate_country_crosswalk <- function(x) {
  if (!is.data.frame(x)) cli::cli_abort("{.arg crosswalk} must be a data frame.")
  needed <- c("year", "gwcode", "ccode")
  absent <- setdiff(needed, names(x))
  if (length(absent)) cli::cli_abort("{.arg crosswalk} lacks columns: {absent}.")
  out <- as.data.frame(x[needed], stringsAsFactors = FALSE)
  for (column in needed) out[[column]] <- integer_value(out[[column]], column)
  unique(out)
}

#' Assign UCDP events to PRIO-GRID cells
#'
#' Converts event coordinates to points and extracts the `pgid` from the grid
#' produced by `priogrid::prio_blank_grid()`. A pre-built `SpatRaster` can be
#' supplied to freeze the exact grid configuration or test the workflow
#' offline. The function targets the released `priogrid` package; the simple
#' `pgid` output is also intended as a stable bridge for future grid tooling.
#'
#' @param data A data frame with coordinates or an `sf` point object.
#' @param longitude,latitude Optional coordinate columns passed to
#'   [ucdp_as_sf()].
#' @param grid Optional `terra` `SpatRaster` whose cell values are PRIO-GRID
#'   identifiers. If omitted, `priogrid::prio_blank_grid()` is used.
#' @param config Optional `priogrid` configuration passed to
#'   `prio_blank_grid()`. Ignored when `grid` is supplied.
#' @param pgid Name of the output identifier column.
#' @param missing Handling of missing coordinates or cells outside the grid.
#' @return A tibble (or `sf` object when the input is `sf`) with a PRIO-GRID
#'   identifier and preserved UCDP provenance.
#' @export
#' @examples
#' events <- data.frame(id = 1:2, longitude = c(10, 20), latitude = c(50, 60))
#' # Requires the optional priogrid, terra, and sf packages:
#' if (FALSE) ucdp_to_priogrid(events)
ucdp_to_priogrid <- function(data, longitude = NULL, latitude = NULL,
                             grid = NULL, config = NULL, pgid = "pgid",
                             missing = c("keep", "drop", "error")) {
  if (!is.data.frame(data)) cli::cli_abort("{.arg data} must be a data frame.")
  missing <- match.arg(missing)
  pgid <- scalar_name(pgid, "pgid")
  require_optional("sf", "assign UCDP events to PRIO-GRID cells")
  require_optional("terra", "assign UCDP events to PRIO-GRID cells")
  source <- attr(data, "ucdp_source", exact = TRUE)
  was_sf <- inherits(data, "sf")
  points <- ucdp_as_sf(data, longitude = longitude, latitude = latitude,
                       crs = 4326, missing = if (missing == "drop") "drop" else "keep")
  if (is.null(grid)) {
    require_optional("priogrid", "create the configured PRIO-GRID raster")
    blank_grid <- getExportedValue("priogrid", "prio_blank_grid")
    grid <- if (is.null(config)) blank_grid() else blank_grid(config)
  } else if (!is.null(config)) {
    cli::cli_warn("{.arg config} is ignored because {.arg grid} was supplied.")
  }
  if (!inherits(grid, "SpatRaster") || terra::nlyr(grid) != 1L) {
    cli::cli_abort("{.arg grid} must be a one-layer {.cls SpatRaster} containing cell identifiers.")
  }
  transformed <- sf::st_transform(points, terra::crs(grid, proj = TRUE))
  values <- rep(NA_real_, nrow(points))
  complete <- !sf::st_is_empty(transformed)
  if (any(complete)) {
    xy <- sf::st_coordinates(transformed[complete, , drop = FALSE])
    extracted <- terra::extract(grid, xy[, 1:2, drop = FALSE])
    values[complete] <- extracted[[1L]]
  }
  points[[pgid]] <- values
  missed <- is.na(values)
  if (any(missed) && missing == "error") {
    cli::cli_abort("No PRIO-GRID cell was assigned to {sum(missed)} row(s).")
  }
  if (missing == "drop") points <- points[!missed, , drop = FALSE]
  out <- if (was_sf) points else tibble::as_tibble(sf::st_drop_geometry(points))
  if (!is.null(source)) attr(out, "ucdp_source") <- source
  attr(out, "ucdp_priogrid") <- list(pgid = pgid, matched = sum(!missed), unmatched = sum(missed))
  out
}

#' Prepare UCDP data for peacesciencer workflows
#'
#' `ucdp_to_peacesciencer()` standardizes state-year or dyad-year keys to the
#' names expected by `peacesciencer` and declares the corresponding package
#' attributes. It does not aggregate event data automatically; use
#' [ucdp_aggregate()] first when observations are not already unique at the
#' requested unit.
#'
#' @param data A state-year or dyad-year data frame.
#' @param type `"state-year"` or `"dyad-year"`.
#' @param system Target state system: `"gw"` or `"cow"`.
#' @param code,code2 Source code columns. `code2` is required for dyad-years.
#' @param year Year column.
#' @param from Coding system of the supplied codes. Defaults to `system`. If it
#'   differs, codes are converted with [ucdp_country_crosswalk()].
#' @param crosswalk Optional frozen crosswalk passed to
#'   [ucdp_country_crosswalk()].
#' @param check_unique Require one row per state-year or dyad-year key?
#' @return A data frame with `year` and `gwcode`/`ccode` keys (or numbered
#'   dyadic variants) and `peacesciencer` attributes.
#' @export
#' @examples
#' x <- data.frame(country_id = c(2, 20), year = 2020, events = c(1, 3))
#' if (requireNamespace("peacesciencer", quietly = TRUE)) {
#'   ps <- ucdp_to_peacesciencer(x, code = "country_id")
#' }
ucdp_to_peacesciencer <- function(data, type = c("state-year", "dyad-year"),
                                  system = c("gw", "cow"), code = NULL,
                                  code2 = NULL, year = "year", from = system,
                                  crosswalk = NULL, check_unique = TRUE) {
  if (!is.data.frame(data)) cli::cli_abort("{.arg data} must be a data frame.")
  type <- match.arg(type)
  system <- match.arg(system)
  from <- match.arg(from, c("gw", "cow"))
  validate_flag(check_unique, "check_unique")
  require_optional("peacesciencer", "prepare data for peacesciencer workflows")
  year <- scalar_column(data, year, "year")
  candidates <- if (from == "gw") c("gwcode", "gwno", "country_id") else "ccode"
  code <- resolve_interop_column(data, code, candidates, "code")
  if (type == "dyad-year") {
    code2 <- resolve_interop_column(data, code2,
      if (from == "gw") c("gwcode2", "gwno_b", "side_b_id") else "ccode2", "code2")
  }
  source <- attr(data, "ucdp_source", exact = TRUE)
  out <- as.data.frame(data, stringsAsFactors = FALSE)
  out$year <- integer_value(out[[year]], year)
  target <- if (system == "gw") "gwcode" else "ccode"

  convert_one <- function(values, name) {
    temporary <- data.frame(.code = values, year = out$year)
    if (from == system) return(integer_value(values, name))
    converted <- ucdp_country_crosswalk(
      temporary, from = from, code = ".code", crosswalk = crosswalk,
      unmatched = "warn"
    )
    converted[[target]]
  }
  if (type == "state-year") {
    out[[target]] <- convert_one(out[[code]], code)
    keys <- c(target, "year")
  } else {
    out[[paste0(target, "1")]] <- convert_one(out[[code]], code)
    out[[paste0(target, "2")]] <- convert_one(out[[code2]], code2)
    keys <- c(paste0(target, 1:2), "year")
  }
  if (check_unique && anyDuplicated(out[keys])) {
    cli::cli_abort(c(
      "The requested peacesciencer keys are not unique.",
      "i" = "Aggregate or otherwise resolve duplicate {type} observations first."
    ))
  }
  out <- peacesciencer::declare_attributes(
    tibble::as_tibble(out), data_type = gsub("-", "_", type), system = system
  )
  if (!is.null(source)) attr(out, "ucdp_source") <- source
  attr(out, "ucdp_interoperability") <- list(type = type, system = system, keys = keys)
  out
}

resolve_interop_column <- function(data, supplied, candidates, argument) {
  if (!is.null(supplied)) return(scalar_column(data, supplied, argument))
  found <- candidates[candidates %in% names(data)]
  if (!length(found)) {
    cli::cli_abort("Could not detect {.arg {argument}}; supply its column name explicitly.")
  }
  found[[1L]]
}

scalar_column <- function(data, value, argument) {
  value <- scalar_name(value, argument)
  if (!value %in% names(data)) cli::cli_abort("Column {.field {value}} was not found in {.arg data}.")
  value
}

scalar_name <- function(value, argument) {
  if (!is.character(value) || length(value) != 1L || is.na(value) || !nzchar(value)) {
    cli::cli_abort("{.arg {argument}} must be one non-empty column name.")
  }
  value
}

integer_value <- function(x, name) {
  out <- suppressWarnings(as.integer(as.character(x)))
  invalid <- !is.na(x) & nzchar(trimws(as.character(x))) & is.na(out)
  if (any(invalid)) cli::cli_abort("Column {.field {name}} contains non-integer values.")
  out
}
