#' ucdpR: Tools for working with UCDP data
#'
#' `ucdpR` supports reproducible research with data from the Uppsala Conflict
#' Data Program (UCDP). It discovers, downloads, and imports current and
#' historical releases from the official UCDP download center, preserves
#' provenance information, retrieves official codebooks, and provides
#' convenience functions for inspecting, validating, spatially preparing,
#' aggregating, panelizing, and comparing UCDP data. It also exposes official
#' version histories and publication-specific replication materials. The
#' package is intended to grow into a broader toolkit for common UCDP research
#' workflows. It does not redistribute UCDP data.
#'
#' @keywords internal
